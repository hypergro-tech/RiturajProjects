// pdf.js renders PDFs that reference the 14 standard fonts without embedding them only if it can fetch
// those fonts. Copy them from the package into public/ so the built app serves them at /pdf-standard-fonts/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// It also writes src/generated/standardFonts.ts (the same files as base64) for the single-file artifact
// build, whose page cannot fetch anything at runtime.
const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../node_modules/pdfjs-dist/standard_fonts');
const dst = path.resolve(here, '../public/pdf-standard-fonts');
const gen = path.resolve(here, '../src/generated/standardFonts.ts');
fs.mkdirSync(dst, { recursive: true });
fs.mkdirSync(path.dirname(gen), { recursive: true });
let n = 0;
const entries = [];
for (const f of fs.readdirSync(src)) {
  fs.copyFileSync(path.join(src, f), path.join(dst, f));
  n++;
  if (/\.(pfb|ttf)$/i.test(f)) entries.push(`  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(src, f)).toString('base64'))},`);
}
fs.writeFileSync(gen, `// Generated by scripts/copy-pdf-fonts.mjs — pdf.js standard fonts as base64 for the artifact build.\nexport const STANDARD_FONTS: Record<string, string> = {\n${entries.join('\n')}\n};\n`);
console.log(`[copy-pdf-fonts] ${n} files → public/pdf-standard-fonts · ${entries.length} fonts → src/generated/standardFonts.ts`);
